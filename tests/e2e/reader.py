from playwright.sync_api import sync_playwright
import os, sys, tempfile
BASE = os.environ.get("BASE", "http://localhost:4173")
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
AXE = os.path.join(ROOT, "node_modules", "axe-core", "axe.min.js")
S = tempfile.mkdtemp(prefix="e2e-shots-")
res=[]; errs=[]
def ok(n,c): res.append((n,bool(c)))
def axe(pg,name):
    pg.add_script_tag(path=AXE)
    r=pg.evaluate("axe.run(document,{runOnly:['wcag2a','wcag2aa']}).then(r=>r.violations.map(v=>v.id+':'+v.nodes.length+':'+(v.nodes[0].target.join(' ')).slice(0,70)))")
    print('AXE',name,r)
with sync_playwright() as p:
    b=p.chromium.launch()
    def page(route,w=1280,h=900):
        pg=b.new_page(viewport={'width':w,'height':h})
        pg.on('console', lambda m: errs.append((route,m.text)) if m.type=='error' else None)
        pg.on('pageerror', lambda e: errs.append((route,'PAGEERR '+str(e))))
        pg.goto(f'{BASE}/#/{route}'); pg.wait_for_timeout(400); return pg
    # NOW
    pg=page('reader/now')
    ok('now stats consistent', pg.get_by_text('2 books behind pace').count()==1)
    inp=pg.get_by_label('Page you are on in Piranesi'); inp.fill('999')
    ok('now invalid page error', pg.get_by_role('alert').filter(has_text='from 0 to 272').count()==1)
    inp.fill('250'); pg.keyboard.press('Enter')
    ok('now progress update', pg.get_by_role('status').filter(has_text='updated to page 250').count()==1)
    pg.get_by_label('Page you are on in Piranesi').fill('272'); pg.keyboard.press('Enter')
    ok('now finish banner', pg.get_by_role('status').filter(has_text='Finished Piranesi').count()==1)
    ok('now count 15', pg.get_by_text('Finished Piranesi. That is 15 of 20').count()==1)
    ok('now reading count 2', 'reading 2 books' in pg.locator('h1').inner_text())
    pg.get_by_role('button',name='Show all 7 reviews').click()
    ok('now show all reviews', pg.locator('.now__review').count()>=7 or pg.locator('.now__review').count()==8)
    pg.get_by_role('button',name='Want to read').click(); pg.wait_for_timeout(300)
    ok('now shelf sheet', pg.get_by_role('dialog',name='Want to read').is_visible())
    axe(pg,'now sheet'); pg.keyboard.press('Escape')
    axe(pg,'now')
    # empty state
    for t,n in [('The Overstory',502),('Braiding Sweetgrass',391)]:
        pg.get_by_label(f'Page you are on in {t}').fill(str(n)); pg.keyboard.press('Enter')
    ok('now empty state', pg.get_by_text('Nothing on the nightstand').count()==1)
    pg.get_by_role('button',name='Start').first.click()
    ok('now start from want', 'reading one book' in pg.locator('h1').inner_text())
    pg.close()
    # YEAR
    pg=page('reader/year')
    ok('year headline', '14 books' in pg.locator('h1').inner_text())
    ok('year chart label', '16 expected' in pg.locator('.yc svg').get_attribute('aria-label') or pg.get_by_text('16 expected').count()>=1)
    pg.get_by_role('button',name='Pages',exact=True).click()
    ok('year pages view', pg.get_by_role('heading',name='Pages per month').count()==1)
    pg.locator('.year__select select').select_option('10')
    ok('year month filter', pg.locator('.year__finished li').count()==2)
    pg.locator('.year__select select').select_option('2')
    ok('year month Feb', pg.locator('.year__finished li').count()==1)
    axe(pg,'year'); pg.close()
    pg=page('reader/year',390,844)
    ok('year mobile chart fits', pg.evaluate('document.documentElement.scrollWidth<=innerWidth')); pg.close()
    # SHELVES
    pg=page('reader/shelves')
    pg.get_by_role('button',name='Want to read · 5').click()
    ok('shelves filter', pg.locator('.sh__grid li').count()==5)
    pg.locator('.sh__select select').nth(0).select_option('Sci-fi')
    ok('shelves genre', pg.locator('.sh__grid li').count()==2)
    pg.get_by_role('button',name='All · 23').click(); pg.locator('.sh__select select').nth(0).select_option('all')
    pg.locator('.sh__select select').nth(1).select_option('title')
    ok('shelves sort', 'A Gentleman' in pg.locator('.sh__book').first.get_attribute('aria-label'))
    pg.get_by_role('button',name='Currently reading · 3').click()
    pg.get_by_role('button',name='Piranesi by Susanna Clarke').click(); pg.wait_for_timeout(300)
    ok('shelves sheet', pg.get_by_role('dialog',name='Piranesi').is_visible())
    pg.get_by_label('Current page').fill('272'); pg.get_by_role('button',name='Update').click(); pg.wait_for_timeout(300)
    ok('shelves finish closes + moves', pg.get_by_role('dialog').count()==0 or not pg.get_by_role('dialog').is_visible())
    pg.get_by_role('button',name='Read · 15').click()
    pg.get_by_role('button',name='Circe by Madeline Miller').click(); pg.wait_for_timeout(300)
    pg.locator('.rating-input__star').nth(1).click()
    pg.get_by_label('Your review').fill('Changed my mind about the ending.')
    pg.get_by_role('button',name='Save review').click()
    ok('shelves review saved', pg.get_by_role('button',name='Saved').count()==1)
    axe(pg,'shelves sheet')
    pg.locator('.sh-detail select').select_option('want'); pg.wait_for_timeout(200)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    ok('shelves moved to want', pg.get_by_role('button',name='Read · 14').count()==1)
    axe(pg,'shelves'); pg.close()
    pg=page('reader/shelves',390,844)
    pg.get_by_role('button',name='Dune by Frank Herbert').click(); pg.wait_for_timeout(300)
    ok('shelves mobile bottom sheet', pg.get_by_role('dialog',name='Dune').is_visible())
    pg.screenshot(path=f'{S}/shelves-sheet-390.png'); pg.close()
    b.close()
for n,c in res: print('PASS' if c else 'FAIL', n)
print('ERRS',errs)
sys.exit(1 if (any(not c for _, c in res) or errs) else 0)
