from playwright.sync_api import sync_playwright
import os, sys, tempfile
BASE = os.environ.get("BASE", "http://localhost:4173")
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
AXE = os.path.join(ROOT, "node_modules", "axe-core", "axe.min.js")
S = tempfile.mkdtemp(prefix="e2e-shots-")
res=[]; errs=[]
def ok(n,c): res.append((n,bool(c)))
def axe(pg,name):
    pg.add_script_tag(path=AXE)
    r=pg.evaluate("axe.run(document,{runOnly:['wcag2a','wcag2aa']}).then(r=>r.violations.map(v=>v.id+':'+v.nodes.length+':'+(v.nodes[0].target.join(' ')).slice(0,70)))")
    print('AXE',name,r)
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=b.new_page(viewport={'width':1280,'height':900})
    pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.goto(f'{BASE}/#/booking/flow'); pg.wait_for_timeout(400)
    cont=pg.get_by_role('button',name='Continue')
    ok('step1 continue disabled until choice', cont.is_disabled())
    axe(pg,'booking step1')
    pg.locator('.bk__service').nth(1).click()
    ok('step1 choice enables continue', cont.is_enabled())
    cont.click()
    ok('focus moves to step heading', pg.evaluate("document.activeElement.id")=='step-h')
    ok('step2 progress label', pg.get_by_text('Step 2 of 4: Time').count()==1)
    ok('step2 continue disabled until time', pg.get_by_role('button',name='Continue').is_disabled())
    disabled=pg.locator('.bk__slots button:disabled').count()
    ok('some slots unavailable', disabled>0)
    pg.locator('.bk__slots button:not(:disabled)').first.click()
    ok('slot pressed', pg.locator('.bk__slots button[aria-pressed=true]').count()==1)
    pg.get_by_label('Clinician').select_option('mei')
    ok('changing clinician clears time', pg.get_by_role('button',name='Continue').is_disabled())
    pg.locator('.bk__slots button:not(:disabled)').first.click()
    axe(pg,'booking step2')
    pg.get_by_role('button',name='Continue').click()
    pg.get_by_role('button',name='Continue').click()
    ok('step3 validation errors', pg.get_by_role('alert').count()==2)
    pg.get_by_label('Full name').fill('Sam Rivera'); pg.get_by_label('Email').fill('sam@example.com')
    axe(pg,'booking step3')
    pg.get_by_role('button',name='Continue').click()
    ok('step4 summary', pg.get_by_text('Sam Rivera').count()>=1 and pg.get_by_text('Follow-up').count()>=1)
    pg.get_by_role('button',name='Back').click()
    ok('back keeps details', pg.get_by_label('Full name').input_value()=='Sam Rivera')
    pg.get_by_role('button',name='Continue').click()
    pg.get_by_role('button',name='Confirm booking').click()
    ok('confirmation', pg.get_by_role('heading',name='You are booked, Sam.').count()==1)
    ok('confirmation focus on h1', pg.evaluate("document.activeElement.tagName")=='H1')
    ok('honest demo note', pg.get_by_text('nothing was sent').count()==1)
    axe(pg,'booking done')
    pg.get_by_role('button',name='Book another visit').click()
    ok('reset', pg.get_by_text('Step 1 of 4').count()==1)
    pg.close()
    pg=b.new_page(viewport={'width':390,'height':844}); pg.goto(f'{BASE}/#/booking/flow'); pg.wait_for_timeout(300)
    ok('mobile summary details present', pg.locator('details.bk__mobile-summary').is_visible())
    ok('mobile aside hidden', not pg.locator('.bk__aside').is_visible())
    pg.locator('.bk__service').nth(0).click(); pg.get_by_role('button',name='Continue').click(); pg.wait_for_timeout(200)
    pg.screenshot(path=f'{S}/book-step2-390.png', full_page=True)
    ok('mobile no overflow step2', pg.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    pg.close(); b.close()
for n,c in res: print('PASS' if c else 'FAIL', n)
print('ERRS',errs)
sys.exit(1 if (any(not c for _, c in res) or errs) else 0)
