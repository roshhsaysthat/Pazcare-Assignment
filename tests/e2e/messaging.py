AXE = os.path.join(ROOT, "node_modules", "axe-core", "axe.min.js")
S = tempfile.mkdtemp(prefix="e2e-shots-")
res=[]; errs=[]
def ok(name, cond): res.append((name, bool(cond)))
def axe(pg, name):
    pg.add_script_tag(path=AXE)
    r=pg.evaluate("axe.run(document,{runOnly:['wcag2a','wcag2aa']}).then(r=>r.violations.map(v=>v.id+':'+v.nodes.length+':'+(v.nodes[0].target.join(' ')).slice(0,60)))")
    print('AXE',name,r)
