    b=p.chromium.launch()
    def page(cid,w=1280,h=800):
        pg=b.new_page(viewport={'width':w,'height':h})
        pg.on('console', lambda m: errs.append((cid,m.text)) if m.type=='error' else None)
        pg.on('pageerror', lambda e: errs.append((cid,'PAGEERR '+str(e))))
        pg.goto(f'{BASE}/#/messaging/{cid}'); pg.wait_for_timeout(400); return pg
